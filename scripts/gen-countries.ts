// Generates the full country list (ISO code + English name) and copies flag SVGs to public/flags.
// Run once after install: npx tsx scripts/gen-countries.ts (needs devDependency country-flag-icons)
import fs from "node:fs";
import path from "node:path";

const src = path.join(process.cwd(), "node_modules", "country-flag-icons", "3x2");
const out = path.join(process.cwd(), "public", "flags");
fs.mkdirSync(out, { recursive: true });

const names = new Intl.DisplayNames(["en"], { type: "region" });
const rows: [string, string][] = [];
for (const file of fs.readdirSync(src)) {
  const code = file.replace(".svg", "");
  if (!/^[A-Z]{2}$/.test(code)) continue;
  let name: string | undefined;
  try {
    name = names.of(code);
  } catch {
    continue;
  }
  if (!name || name === code) continue;
  fs.copyFileSync(path.join(src, file), path.join(out, file));
  rows.push([code, name]);
}
rows.sort((a, b) => a[1].localeCompare(b[1]));

const ts = `// Generated by scripts/gen-countries.ts — do not edit by hand.
export const ALL_COUNTRIES: readonly (readonly [code: string, name: string])[] = ${JSON.stringify(rows)};
`;
fs.writeFileSync(path.join(process.cwd(), "src", "lib", "countries.ts"), ts);
console.log(`${rows.length} countries, flags in public/flags`);
